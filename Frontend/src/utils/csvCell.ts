/**
 * ช่องหนึ่งช่องของไฟล์ CSV ที่เปิดด้วย Excel
 * - ครอบด้วย "..." และ "" แทน " (ข้อความมีจุลภาค/ขึ้นบรรทัดใหม่ได้)
 * - ข้อความที่ผู้ใช้พิมพ์ขึ้นต้นด้วย = + - @ (หรือ tab/CR) Excel ตีความเป็นสูตรแม้อยู่ใน "..."
 *   เช่นบันทึกประจำวัน `=HYPERLINK("https://เว็บหลอก","คลิก")` → ใส่ ' นำหน้าให้เป็นข้อความ (OWASP CSV injection)
 *   "- ทำงาน" (ขีดแล้วเว้นวรรค = รายการ) ไม่ใช่สูตร คงไว้ตามเดิม
 */
export function csvCell(v: unknown): string {
  let s = v == null ? "" : String(v);
  if (/^[=+@\t\r]/.test(s) || /^-(?! )/.test(s)) s = `'${s}`;
  return `"${s.replace(/"/g, '""')}"`;
}
